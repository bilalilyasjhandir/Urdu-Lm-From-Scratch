"""Describe the cleaned corpus: size, document lengths, sites, character inventory.

    python scripts/03_stats.py --data-dir D:/urdu-lm-data

Writes reports/corpus_stats.json and reports/corpus_stats.md in the repository.
The character inventory decides the vocabulary of the character-level model, and
the site concentration shows how much of the corpus a handful of websites supply.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import unicodedata
from collections import Counter
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq

REPO = Path(__file__).resolve().parents[1]


def shard_stats(path: str) -> dict:
    table = pq.read_table(path, columns=["text", "domain"])
    chars: Counter = Counter()
    domain_chars: Counter = Counter()
    lengths = []
    words = 0
    for text, domain in zip(table.column("text").to_pylist(), table.column("domain").to_pylist()):
        chars.update(text)
        domain_chars[domain] += len(text)
        lengths.append(len(text))
        words += len(text.split())
    return {"docs": len(lengths), "words": words, "chars": chars,
            "domain_chars": domain_chars, "lengths": np.asarray(lengths, dtype=np.int64)}


def summarise(paths: list[Path], workers: int) -> dict:
    chars: Counter = Counter()
    domain_chars: Counter = Counter()
    lengths = []
    docs = words = 0
    with ProcessPoolExecutor(max_workers=workers) as pool:
        for i, res in enumerate(pool.map(shard_stats, [str(p) for p in paths]), start=1):
            docs += res["docs"]
            words += res["words"]
            chars.update(res["chars"])
            domain_chars.update(res["domain_chars"])
            lengths.append(res["lengths"])
            print(f"  {i}/{len(paths)} shards", flush=True)
    lengths_all = np.concatenate(lengths) if lengths else np.zeros(0, dtype=np.int64)
    total_chars = int(lengths_all.sum())
    by_count = chars.most_common()
    cumulative = np.cumsum([c for _, c in by_count]) / max(1, total_chars)
    top_domains = domain_chars.most_common(20)
    sorted_domain = np.sort(np.fromiter(domain_chars.values(), dtype=np.int64))[::-1]
    return {
        "docs": docs,
        "chars": total_chars,
        "words": words,
        "chars_per_word": round(total_chars / max(1, words), 3),
        "doc_chars_quantiles": {str(q): int(np.quantile(lengths_all, q / 100)) for q in (1, 10, 25, 50, 75, 90, 99)}
        if docs else {},
        "sites": len(domain_chars),
        "share_of_chars_from_top_sites": {str(k): round(float(sorted_domain[:k].sum()) / max(1, total_chars), 4)
                                          for k in (1, 10, 100, 1000)},
        "top_sites": [{"site": d, "share_of_chars": round(c / max(1, total_chars), 4)} for d, c in top_domains],
        "distinct_chars": len(chars),
        "chars_needed_for_coverage": {str(t): int(np.searchsorted(cumulative, t) + 1)
                                      for t in (0.99, 0.999, 0.9999, 0.99999)},
        "top_chars": [{"char": ch, "codepoint": f"U+{ord(ch):04X}", "name": unicodedata.name(ch, "?"),
                       "share": round(c / max(1, total_chars), 5)} for ch, c in by_count[:60]],
    }


def to_markdown(stats: dict) -> str:
    lines = ["# Corpus statistics", "", "Generated by `scripts/03_stats.py`. Do not edit by hand.", "",
             "| Split | Documents | Characters | Words | Sites |", "|---|---:|---:|---:|---:|"]
    for split, s in stats.items():
        lines.append(f"| {split} | {s['docs']:,} | {s['chars']:,} | {s['words']:,} | {s['sites']:,} |")
    train = stats.get("train")
    if train:
        q = train["doc_chars_quantiles"]
        lines += ["", "## Training split", "",
                  f"- Characters per whitespace word: {train['chars_per_word']}",
                  f"- Document length in characters: median {q.get('50', 0):,}, "
                  f"10th percentile {q.get('10', 0):,}, 90th percentile {q.get('90', 0):,}",
                  f"- Distinct characters: {train['distinct_chars']:,}. "
                  f"The most frequent {train['chars_needed_for_coverage']['0.9999']:,} cover 99.99% of the text.",
                  "- Share of all characters supplied by the largest sites: "
                  + ", ".join(f"top {k}: {v:.1%}" for k, v in train["share_of_chars_from_top_sites"].items()),
                  "", "| Site | Share of characters |", "|---|---:|"]
        lines += [f"| {t['site']} | {t['share_of_chars']:.2%} |" for t in train["top_sites"]]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument("--report-dir", type=Path, default=REPO / "reports")
    parser.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 2))
    args = parser.parse_args()

    clean = args.data_dir / "clean"
    groups = {
        "train": sorted((clean / "train").glob("*.parquet")),
        "val": [clean / "heldout" / "val.parquet"],
        "test": [clean / "heldout" / "test.parquet"],
    }
    if not groups["train"]:
        sys.exit(f"No cleaned shards under {clean / 'train'}. Run scripts/02_clean.py first.")

    stats = {}
    for split, paths in groups.items():
        print(f"[{split}]")
        stats[split] = summarise([p for p in paths if p.exists()], args.workers)

    args.report_dir.mkdir(parents=True, exist_ok=True)
    (args.report_dir / "corpus_stats.json").write_text(json.dumps(stats, indent=2, ensure_ascii=False), encoding="utf-8")
    (args.report_dir / "corpus_stats.md").write_text(to_markdown(stats), encoding="utf-8")
    print(to_markdown(stats))


if __name__ == "__main__":
    main()
